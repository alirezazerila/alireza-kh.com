/* ---------------------------------------------------------------------------
   Home Comfort NY — deployment mode

   "private"  local monitoring platform. Participant names, emails and personal
              details are shown. Served only from this computer (localhost).

   "public"   shared read-only portal (alireza-kh.com). The files for this mode
              are generated by build-public.py, which strips every identifying
              field out of the roster before it is published. Nothing in the
              public build contains a name, an email or a ZIP code.

   The mode is decided by the hostname, so the same index.html is correct in
   both places and there is no switch to remember at deploy time.
--------------------------------------------------------------------------- */
const SITE_MODE = (function(){
  var h = location.hostname;
  var local = (h === "localhost" || h === "127.0.0.1" || h === "::1" ||
               h === "[::1]" || h === "" || /\.localhost$/.test(h));
  return local ? "private" : "public";
})();
